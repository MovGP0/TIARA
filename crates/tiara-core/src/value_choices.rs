/// How many there are.
pub const CHOOSES_COUNT: usize = 868;

/// Implements part of the value-choosing family.
///
/// What one routine does, if it is one of these.
#[must_use]
pub fn chooses_at(routine: u32) -> Option<&'static Chooses> {
    CHOOSES
        .binary_search_by_key(&routine, |held| held.routine)
        .ok()
        .map(|at| &CHOOSES[at])
}

/// Implements part of the value-choosing family.
///
/// Every routine whose question is of one kind.
#[must_use]
pub fn asking(asks: Asks) -> Vec<&'static Chooses> {
    CHOOSES.iter().filter(|held| held.asks == asks).collect()
}

/// Implements part of the value-choosing family.
///
/// What the questions are, commonest first.
#[must_use]
pub fn questions() -> Vec<(Asks, usize)> {
    let mut counted: Vec<(Asks, usize)> = Vec::new();
    for held in &CHOOSES {
        match counted.iter_mut().find(|(asks, _)| *asks == held.asks) {
            Some((_, seen)) => *seen += 1,
            None => counted.push((held.asks, 1)),
        }
    }
    counted.sort_by(|left, right| right.1.cmp(&left.1).then(left.0.cmp(&right.0)));
    counted
}

/// Implements part of the value-choosing family.
///
/// The routines that say what to do on both answers.
#[must_use]
pub fn answer_either_way() -> Vec<&'static Chooses> {
    CHOOSES.iter().filter(|held| held.has_other_side).collect()
}

/// Implements part of the value-choosing family.
///
/// Every routine that reads one kind of thing.
#[must_use]
pub fn reading(reads: Reads) -> Vec<&'static Chooses> {
    CHOOSES
        .iter()
        .filter(|held| held.reads.contains(&reads))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_count_is_what_the_table_holds() {
        assert_eq!(CHOOSES.len(), CHOOSES_COUNT);
    }

    #[test]
    fn the_table_is_sorted_so_it_can_be_searched() {
        assert!(
            CHOOSES
                .windows(2)
                .all(|pair| pair[0].routine < pair[1].routine)
        );
    }

    #[test]
    fn a_routine_can_be_found_by_its_address() {
        let known = CHOOSES[0].routine;

        assert!(chooses_at(known).is_some());
        assert!(chooses_at(0).is_none());
    }

    #[test]
    fn most_of_them_say_what_to_do_on_both_answers() {
        // A value has to be something whichever way the question goes.
        let both = answer_either_way().len();

        assert!(both * 2 > CHOOSES.len(), "{both} of {}", CHOOSES.len());
    }

    #[test]
    fn where_the_routines_that_choose_an_action_usually_do_not() {
        let here = answer_either_way().len() * 100 / CHOOSES.len();
        let there = crate::two_way_routines::act_on_both_answers().len() * 100
            / crate::two_way_routines::CHOICES.len();

        assert!(here > there * 2, "{here}% against {there}%");
    }

    #[test]
    fn joining_two_tests_is_the_commonest_question_here() {
        assert_eq!(questions()[0].0, Asks::TwoTestsJoined);
    }

    #[test]
    fn where_among_the_action_choosing_routines_it_is_among_the_rarest() {
        // A routine that answers whether two things are alike has to ask about
        // both halves of both of them.
        let there = crate::two_way_routines::questions();
        let rank = there
            .iter()
            .position(|(asks, _)| *asks == Asks::TwoTestsJoined)
            .expect("asked there too");

        assert!(rank >= there.len() / 2, "ranked {rank} of {}", there.len());
    }

    #[test]
    fn every_question_kind_is_asked_by_someone() {
        for (_, seen) in questions() {
            assert!(seen > 0);
        }
    }

    #[test]
    fn most_answer_rather_than_writing_somewhere() {
        let answering = CHOOSES.iter().filter(|held| held.answers).count();

        assert!(answering * 2 > CHOOSES.len());
    }

    #[test]
    fn nearly_all_read_something_they_were_given() {
        let given = reading(Reads::WhatItWasGiven).len();

        assert!(given * 10 > CHOOSES.len() * 9);
    }

    #[test]
    fn and_few_touch_anything_shared() {
        let shared = reading(Reads::AGlobal).len();

        assert!(shared * 4 < CHOOSES.len(), "{shared} of {}", CHOOSES.len());
    }

    #[test]
    fn none_of_them_is_long() {
        for held in &CHOOSES {
            assert!(held.statements >= 1, "{:#010X}", held.routine);
            assert!(held.statements <= 14, "{:#010X}", held.routine);
        }
    }

    #[test]
    fn none_of_these_is_already_spoken_for_by_another_sweep() {
        for held in CHOOSES.iter().take(200) {
            assert!(crate::two_way_routines::choice_at(held.routine).is_none());
            assert!(crate::small_computations::computation_at(held.routine).is_none());
            assert!(crate::guarded_routines::guarded_at(held.routine).is_none());
        }
    }

    #[test]
    fn every_routine_is_listed_once() {
        let mut routines: Vec<u32> = CHOOSES.iter().map(|held| held.routine).collect();
        let before = routines.len();
        routines.sort_unstable();
        routines.dedup();

        assert_eq!(routines.len(), before);
    }
}
