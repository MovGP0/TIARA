/// How many there are.
pub const OUTWARD_COUNT: usize = 1470;

/// Implements part of the outward edge.
///
/// What sits at one address, if anything here does.
#[must_use]
pub fn outward_at(at: u32) -> Option<&'static Outward> {
    OUTWARD
        .binary_search_by_key(&at, |held| held.at)
        .ok()
        .map(|found| &OUTWARD[found])
}

/// Implements part of the outward edge.
///
/// Every named import, in address order.
#[must_use]
pub fn imports() -> Vec<&'static Outward> {
    OUTWARD
        .iter()
        .filter(|held| held.reaches == Reaches::Import)
        .collect()
}

/// Implements part of the outward edge.
///
/// Everything imported from one library.
#[must_use]
pub fn from_library(library: &str) -> Vec<&'static Outward> {
    OUTWARD
        .iter()
        .filter(|held| held.reaches == Reaches::Import)
        .filter(|held| held.library == Some(library))
        .collect()
}

/// Implements part of the outward edge.
///
/// Every library named, with how much is taken from it, most first.
#[must_use]
pub fn libraries() -> Vec<(&'static str, usize)> {
    let mut counted: Vec<(&'static str, usize)> = Vec::new();
    for held in OUTWARD
        .iter()
        .filter(|held| held.reaches == Reaches::Import)
    {
        let Some(library) = held.library else {
            continue;
        };
        match counted.iter_mut().find(|(named, _)| *named == library) {
            Some((_, seen)) => *seen += 1,
            None => counted.push((library, 1)),
        }
    }
    counted.sort_by(|left, right| right.1.cmp(&left.1).then(left.0.cmp(right.0)));
    counted
}

/// Implements part of the outward edge.
///
/// The delay-load stub standing in front of one import, if it has one.
///
/// It sits [`STUB_OFFSET`] before it, which is the layout the linker produced.
#[must_use]
pub fn stub_for(held: &Outward) -> Option<&'static Outward> {
    if held.reaches != Reaches::Import {
        return None;
    }
    outward_at(held.at.checked_sub(STUB_OFFSET)?)
        .filter(|stub| stub.reaches == Reaches::DelayLoadStub)
}

/// Implements part of the outward edge.
///
/// Whether an import is fetched only when something first wants it.
#[must_use]
pub fn is_delay_loaded(held: &Outward) -> bool {
    stub_for(held).is_some()
}

/// Implements part of the outward edge.
///
/// Every import the program must have before it can run at all.
///
/// The ones with no stub in front of them. A feature behind a stub is one the
/// program was built to work without; these are not features.
#[must_use]
pub fn needed_at_once() -> Vec<&'static Outward> {
    OUTWARD
        .iter()
        .filter(|held| held.reaches == Reaches::Import)
        .filter(|held| !is_delay_loaded(held))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_count_is_what_the_table_holds() {
        assert_eq!(OUTWARD.len(), OUTWARD_COUNT);
    }

    #[test]
    fn the_table_is_sorted_so_it_can_be_searched() {
        assert!(OUTWARD.windows(2).all(|pair| pair[0].at < pair[1].at));
    }

    #[test]
    fn something_can_be_found_by_its_address() {
        let known = OUTWARD[0].at;

        assert!(outward_at(known).is_some());
        assert!(outward_at(0).is_none());
    }

    #[test]
    fn an_import_names_both_a_library_and_a_function() {
        for held in imports() {
            assert!(held.library.is_some(), "{:#010X}", held.at);
            assert!(held.function.is_some(), "{:#010X}", held.at);
        }
    }

    #[test]
    fn a_thunk_names_neither() {
        for held in OUTWARD.iter().filter(|held| held.reaches == Reaches::Thunk) {
            assert!(held.library.is_none(), "{:#010X}", held.at);
        }
    }

    #[test]
    fn the_biggest_dependency_is_not_the_operating_system() {
        // By the count of named imports, the largest thing outside this program
        // that it depends on is a VHDL simulator.
        let counted = libraries();

        assert_eq!(counted[0].0, "VHDL_DLL2.DLL");
        let windows: usize = counted.iter().skip(1).map(|(_, seen)| *seen).sum();
        assert!(counted[0].1 > windows, "{} against {windows}", counted[0].1);
    }

    #[test]
    fn a_library_can_be_asked_what_is_taken_from_it() {
        let vhdl = from_library("VHDL_DLL2.DLL");

        assert!(!vhdl.is_empty());
        assert!(from_library("NOTHING.DLL").is_empty());
        for held in &vhdl {
            assert_eq!(held.library, Some("VHDL_DLL2.DLL"));
        }
    }

    #[test]
    fn the_simulator_is_fetched_only_when_something_wants_it() {
        // Which is what makes it a feature the program was built to work
        // without, rather than something it needs to start.
        let vhdl = from_library("VHDL_DLL2.DLL");
        let delayed = vhdl.iter().filter(|held| is_delay_loaded(held)).count();

        assert!(delayed * 2 > vhdl.len(), "{delayed} of {}", vhdl.len());
    }

    #[test]
    fn a_stub_sits_exactly_in_front_of_what_it_stands_for() {
        for held in imports().iter().filter(|held| is_delay_loaded(held)) {
            let stub = stub_for(held).expect("it is delay loaded");

            assert_eq!(held.at - stub.at, STUB_OFFSET, "{:#010X}", held.at);
            assert_eq!(
                stub.function.map(|name| name.trim_start_matches('_')),
                held.function.map(|name| name.trim_start_matches('_')),
                "{:#010X}",
                held.at
            );
        }
    }

    #[test]
    fn some_imports_are_needed_before_anything_can_run() {
        let at_once = needed_at_once();

        assert!(!at_once.is_empty());
        assert!(at_once.len() < imports().len());
        for held in &at_once {
            assert!(stub_for(held).is_none(), "{:#010X}", held.at);
        }
    }

    #[test]
    fn a_stub_is_not_itself_an_import() {
        for held in OUTWARD
            .iter()
            .filter(|held| held.reaches == Reaches::DelayLoadStub)
        {
            assert!(stub_for(held).is_none(), "{:#010X}", held.at);
        }
    }

    #[test]
    fn most_of_them_jump_through_a_slot_the_loader_fills_in() {
        let through = OUTWARD.iter().filter(|held| held.slot.is_some()).count();

        assert!(
            through > OUTWARD.len() / 2,
            "{through} of {}",
            OUTWARD.len()
        );
    }

    #[test]
    fn every_kind_is_represented() {
        for kind in [
            Reaches::Import,
            Reaches::DelayLoadStub,
            Reaches::Thunk,
            Reaches::Other,
        ] {
            assert!(
                OUTWARD.iter().any(|held| held.reaches == kind),
                "{kind:?} is missing"
            );
        }
    }

    #[test]
    fn everything_is_listed_once() {
        let mut places: Vec<u32> = OUTWARD.iter().map(|held| held.at).collect();
        let before = places.len();
        places.sort_unstable();
        places.dedup();

        assert_eq!(places.len(), before);
    }
}
