//! What the program reaches for outside itself.
//!
//! 1470 recovered files are not routines of this program at all. They are the
//! edge of it: 279 named imports across 13 libraries, 262 delay-load stubs
//! standing in front of them, and 927 jump thunks going through a slot the
//! loader fills in. Nothing here has a body worth porting — the body is one
//! indirect jump — but together they say exactly what this program cannot do
//! by itself, which nothing else in the recovered code says.
//!
//! The answer is not mostly the operating system. **226 of the 279 named imports
//! are from `VHDL_DLL2.DLL`**, against 53 from every Windows library put
//! together. By this measure the largest thing outside this program that it
//! depends on is a VHDL simulator.
//!
//! And it does not need that simulator to start. 222 of the 262 delay-load stubs
//! stand in front of a VHDL import, which means the library is asked for the
//! first time something wants it rather than when the program loads. Only 19
//! imports have no stub in front of them at all; those are the ones required
//! before anything can run. A feature behind a delay-load stub is a feature the
//! program was built to work without.
//!
//! The stubs sit immediately in front of what they stand for: 260 of the 262 are
//! exactly `0x10` before an import of the same name. That is the layout rather
//! than a coincidence, and [`stub_for`] relies on it.

// The addresses are written without separators so the port-mapping importer can
// match them against the recovered functions.
