/// How many there are.
pub const ITERATES_COUNT: usize = 393;

/// Implements part of the loop family.
///
/// What one routine does, if it is one of these.
#[must_use]
pub fn iterates_at(routine: u32) -> Option<&'static Iterates> {
    ITERATES
        .binary_search_by_key(&routine, |held| held.routine)
        .ok()
        .map(|at| &ITERATES[at])
}

/// Implements part of the loop family.
///
/// Every routine whose loop is of one shape.
#[must_use]
pub fn shaped(shape: Loop) -> Vec<&'static Iterates> {
    ITERATES.iter().filter(|held| held.shape == shape).collect()
}

/// Implements part of the loop family.
///
/// The shapes in use, commonest first.
#[must_use]
pub fn shapes() -> Vec<(Loop, usize)> {
    let mut counted: Vec<(Loop, usize)> = Vec::new();
    for held in &ITERATES {
        match counted.iter_mut().find(|(shape, _)| *shape == held.shape) {
            Some((_, seen)) => *seen += 1,
            None => counted.push((held.shape, 1)),
        }
    }
    counted.sort_by(|left, right| right.1.cmp(&left.1).then(left.0.cmp(&right.0)));
    counted
}

/// Implements part of the loop family.
///
/// The routines whose loop calls nothing.
///
/// The work of the round is done by arithmetic, not by calling out — a walk over
/// something that adds up or copies rather than one that does something to each
/// item.
#[must_use]
pub fn loops_that_call_nothing() -> Vec<&'static Iterates> {
    ITERATES
        .iter()
        .filter(|held| held.inside.is_empty())
        .collect()
}

/// Implements part of the loop family.
///
/// The routines that call nothing outside the loop.
///
/// Everything they do, they do per round. A routine here has no setting up and
/// no finishing off, which is what a plain walk over something looks like.
#[must_use]
pub fn all_the_work_is_in_the_round() -> Vec<&'static Iterates> {
    ITERATES
        .iter()
        .filter(|held| held.outside.is_empty())
        .collect()
}

/// Implements part of the loop family.
///
/// Everything called inside a loop, and how often, commonest first.
#[must_use]
pub fn called_each_round(how_many: usize) -> Vec<(u32, usize)> {
    let mut counted: Vec<(u32, usize)> = Vec::new();
    for call in ITERATES.iter().flat_map(|held| held.inside.iter()) {
        match counted.iter_mut().find(|(at, _)| at == call) {
            Some((_, seen)) => *seen += 1,
            None => counted.push((*call, 1)),
        }
    }
    counted.sort_by(|left, right| right.1.cmp(&left.1).then(left.0.cmp(&right.0)));
    counted.truncate(how_many);
    counted
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_count_is_what_the_table_holds() {
        assert_eq!(ITERATES.len(), ITERATES_COUNT);
    }

    #[test]
    fn the_table_is_sorted_so_it_can_be_searched() {
        assert!(
            ITERATES
                .windows(2)
                .all(|pair| pair[0].routine < pair[1].routine)
        );
    }

    #[test]
    fn a_routine_can_be_found_by_its_address() {
        let known = ITERATES[0].routine;

        assert!(iterates_at(known).is_some());
        assert!(iterates_at(0).is_none());
    }

    #[test]
    fn every_routine_calls_something_somewhere() {
        for held in &ITERATES {
            assert!(
                !held.inside.is_empty() || !held.outside.is_empty(),
                "{:#010X}",
                held.routine
            );
        }
    }

    #[test]
    fn the_commonest_loop_runs_its_body_before_asking_anything() {
        // So a reader cannot assume any of these bodies is skipped.
        assert_eq!(shapes()[0].0, Loop::UntilSomethingHolds);
    }

    #[test]
    fn and_it_is_commoner_than_either_of_the_others() {
        let counted = shapes();

        assert!(counted[0].1 > counted[1].1);
        assert!(counted[0].1 > counted[2].1);
    }

    #[test]
    fn all_three_shapes_are_used() {
        assert_eq!(shapes().len(), 3);
        for (shape, _) in shapes() {
            assert!(!shaped(shape).is_empty(), "{shape:?}");
        }
    }

    #[test]
    fn some_loops_call_nothing_at_all_in_the_round() {
        // The work is arithmetic rather than calling out.
        assert!(!loops_that_call_nothing().is_empty());
    }

    #[test]
    fn and_many_do_nothing_outside_the_round() {
        // No setting up and no finishing off, which is what a plain walk over
        // something looks like.
        let plain = all_the_work_is_in_the_round().len();

        assert!(plain > ITERATES.len() / 4, "{plain} of {}", ITERATES.len());
    }

    #[test]
    fn but_no_routine_is_empty_on_both_counts() {
        for held in &ITERATES {
            assert!(!held.inside.is_empty() || !held.outside.is_empty());
        }
    }

    #[test]
    fn a_minority_test_anything_inside_the_round() {
        let testing = ITERATES.iter().filter(|held| held.tests_inside).count();

        assert!(testing > 0);
        assert!(
            testing * 2 < ITERATES.len(),
            "{testing} of {}",
            ITERATES.len()
        );
    }

    #[test]
    fn fewer_still_reach_for_what_they_call_each_round() {
        let reaching = ITERATES.iter().filter(|held| held.reaches_inside).count();
        let testing = ITERATES.iter().filter(|held| held.tests_inside).count();

        assert!(reaching < testing);
    }

    #[test]
    fn a_few_routines_are_called_by_many_of_these_loops() {
        let busiest = called_each_round(5);

        assert!(busiest[0].1 > 5, "{busiest:?}");
    }

    #[test]
    fn no_loop_body_is_long() {
        for held in &ITERATES {
            assert!(held.inside.len() <= 5, "{:#010X}", held.routine);
            assert!(held.outside.len() <= 5, "{:#010X}", held.routine);
        }
    }

    #[test]
    fn none_of_these_is_already_spoken_for_by_another_sweep() {
        for held in ITERATES.iter().take(200) {
            assert!(crate::straight_line_routines::sequence_of(held.routine).is_none());
            assert!(crate::two_way_routines::choice_at(held.routine).is_none());
            assert!(crate::guarded_routines::guarded_at(held.routine).is_none());
        }
    }

    #[test]
    fn every_routine_is_listed_once() {
        let mut routines: Vec<u32> = ITERATES.iter().map(|held| held.routine).collect();
        let before = routines.len();
        routines.sort_unstable();
        routines.dedup();

        assert_eq!(routines.len(), before);
    }
}
