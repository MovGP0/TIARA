//! Small routines that choose between two values.
//!
//! 868 of them: one question, and on each answer something worked out rather
//! than something called. As with [`crate::small_computations`], the arithmetic
//! is not reproduced — what is recorded is the question, what the routine reads,
//! how many things it is given, and whether it answers or writes.
//!
//! Set against the routines that choose between two **actions** in
//! [`crate::two_way_routines`], two differences stand out and both make sense.
//! These nearly always have a second side: 522 of the 868 say what to do when the
//! answer is no, where a routine choosing an action usually does not. A value
//! has to be something whichever way the question goes; an action can simply not
//! happen.
//!
//! And the questions are harder. Joining two tests together is the **commonest**
//! question here, where among the action-choosing routines it was among the
//! rarest. A routine that answers whether two things are alike has to ask about
//! both halves of both of them, and that is what most of these are.

// The addresses are written without separators so the port-mapping importer can
// match them against the recovered functions.
#![allow(clippy::unreadable_literal)]

