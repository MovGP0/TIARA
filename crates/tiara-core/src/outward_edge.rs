/// What kind of edge one of these is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Reaches {
    /// A named function in a named library.
    Import,
    /// The stand-in that fetches an import the first time it is wanted.
    DelayLoadStub,
    /// A jump through a slot, with no recovered target.
    Thunk,
    /// Something named that is neither.
    Other,
}

