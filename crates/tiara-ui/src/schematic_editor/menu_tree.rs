//! The Schematic Editor menu, as the original resource defines it.
//!
//! Recovered from the `SchematicEditor.MainMenu` DFM resource: 329 entries, of
//! which 40 open a submenu and 39 are separators. 260 carry the address of the
//! handler the original runs, which is what lets a command be connected to its
//! recovered behaviour rather than guessed from its caption.
//!
//! Two things here are not simply a copy of the resource.
//!
//! 13 entries are marked hidden and 7 start greyed, because the resource says
//! so. `TI Utilities` is one of the hidden ones, which is why the bar carries
//! 9 menus and not 10.
//!
//! And 9 pairs of entries have been merged into one. Each instrument under
//! `T&M` appears in the resource twice under the same caption: once as a
//! submenu offering `Simulated` and `Real-time`, and once as a plain command
//! with a handler. The original shows whichever suits the hardware it finds and
//! hides the other — a Delphi way of switching one menu item between two
//! shapes, rather than two commands. Reproducing both would show every
//! instrument twice, so each pair is one entry here, keeping the command's
//! handler and the submenu's choices.

// The handler addresses are written the way the original names them, without
// the grouping that would otherwise be idiomatic: they are identifiers here.
#![allow(clippy::unreadable_literal)]

/// One entry in the menu.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct MenuEntry {
    /// The text shown, with the accelerator marker removed.
    ///
    /// A separator carries [`SEPARATOR`].
    pub caption: &'static str,
    /// Which character of the caption the original underlines.
    ///
    /// Delphi marks it with a single `&`, which this strips from the caption
    /// and records here, so the underline can be drawn where the original draws
    /// it and the Alt key can reach the same command.
    pub accelerator: Option<usize>,
    /// The name the original resource gives this item, such as `mnNew`.
    ///
    /// This is the item's identity: captions repeat across menus, names do not.
    pub name: &'static str,
    /// The keyboard shortcut shown beside the caption, where the original has one.
    pub shortcut: Option<&'static str>,
    /// Where the original's handler for this item sits.
    ///
    /// `None` for a separator and for the few entries the resource leaves
    /// without an `OnClick`.
    pub handler: Option<u32>,
    /// Whether the resource shows this entry at all.
    pub visible: bool,
    /// Whether the resource starts this entry enabled.
    pub enabled: bool,
    /// The submenu this entry opens, empty when it is a command.
    pub children: &'static [Self],
}

/// The caption a separator carries.
pub const SEPARATOR: &str = "-";

impl MenuEntry {
    /// A separator line.
    #[must_use]
    pub const fn separator() -> Self {
        Self {
            caption: SEPARATOR,
            accelerator: None,
            name: "",
            shortcut: None,
            handler: None,
            visible: true,
            enabled: true,
            children: &[],
        }
    }

    /// Whether this entry draws a separator rather than a command.
    #[must_use]
    pub fn is_separator(&self) -> bool {
        self.caption == SEPARATOR
    }

    /// Whether this entry opens a submenu.
    #[must_use]
    pub const fn opens_a_submenu(&self) -> bool {
        !self.children.is_empty()
    }
}

