//! Routines built around a single loop.
//!
//! 393 of them. What is recorded is the shape of the loop, what is called inside
//! it and what outside, and whether the body tests anything or reaches for what
//! it calls — which for a routine of this shape is most of what there is.
//!
//! The commonest shape by far is the one that runs its body **before** asking
//! whether to go round again: 197 of the 393. That is worth one caution. A loop
//! written as a count from one number to another, where the compiler could see
//! the count was never nought, comes out of a decompiler in exactly this shape
//! too — so the count here is of the recovered form, and it does not settle how
//! many were written that way. What it does settle is that a reader of the
//! recovered code cannot assume any of these bodies is skipped.

// The addresses are written without separators so the port-mapping importer can
// match them against the recovered functions.
#![allow(clippy::unreadable_literal)]

/// The shape of the loop.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Loop {
    /// Walks a count from one number to another.
    OverACount,
    /// Runs the body, then asks whether to go round again.
    UntilSomethingHolds,
    /// Asks first, so the body may not run at all.
    WhileSomethingHolds,
}

/// One routine built around a loop.
#[derive(Debug, Clone, Copy)]
pub struct Iterates {
    /// Where it sits.
    pub routine: u32,
    /// The shape of its loop.
    pub shape: Loop,
    /// What it calls inside the loop, in order.
    pub inside: &'static [u32],
    /// What it calls outside it, in order.
    pub outside: &'static [u32],
    /// Whether it reaches for something it calls inside the loop.
    pub reaches_inside: bool,
    /// Whether the body tests anything.
    pub tests_inside: bool,
}

